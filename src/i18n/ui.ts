// Data dell'edizione formattata nella lingua scelta, nel fuso orario di Udine.
export const formatDate = (iso: string, lang: Lang) => {
  const s = new Intl.DateTimeFormat(languages[lang].locale, {
    weekday: 'long', day: 'numeric', month: 'long', year: 'numeric', timeZone: 'Europe/Rome',
  }).format(new Date(iso));
  return s.charAt(0).toUpperCase() + s.slice(1);
};

// Percorso di una pagina nella lingua scelta: l'italiano sta alla radice.
export const localePath = (lang: Lang, path = '') =>
  (lang === defaultLang ? `/${path}` : `/${lang}/${path}`).replace(/([^/])$/, '$1/');
